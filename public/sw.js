// Kiru Leathers Atelier - Cache-Purging Service Worker
// Ensures every browser (Chrome, Firefox, Safari, Mobile) gets real-time updates without stale caches

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(keys.map((k) => caches.delete(k)));
    }).then(() => {
      return self.clients.claim();
    })
  );
});

// Network-first/pass-through so fresh code is always loaded
self.addEventListener('fetch', (event) => {
  event.respondWith(
    fetch(event.request).catch(() => {
      return caches.match(event.request);
    })
  );
});
